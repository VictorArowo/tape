//! Turning model-written source into a sandboxed strategy.
//!
//! The model only ever writes `src/lib.rs`. The manifest is fixed: one
//! dependency (the guest SDK), no build script, no proc macros of its own,
//! so nothing the model writes runs on this machine at compile time. Before
//! compiling, the source is checked for constructs that could smuggle in
//! information the backtest must not see, such as file contents embedded
//! at compile time or hard-coded dates.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::sync::Mutex;
use std::time::{Duration, Instant};

use thiserror::Error;

#[derive(Debug, Error)]
pub enum BuildError {
    #[error("rejected before compiling: {0}")]
    Rejected(String),
    #[error("didn't compile:\n{0}")]
    Compile(String),
    #[error("build took longer than {0:?}")]
    Timeout(Duration),
    #[error("couldn't run cargo: {0}")]
    Io(#[from] std::io::Error),
}

/// Constructs a strategy may not use, and why.
const FORBIDDEN: &[(&str, &str)] = &[
    ("include_str!", "reads files at compile time"),
    ("include_bytes!", "reads files at compile time"),
    ("include!", "reads files at compile time"),
    ("env!", "reads the build environment"),
    ("option_env!", "reads the build environment"),
    ("#[path", "loads code from other files"),
    ("extern crate", "adds dependencies"),
    ("asm!", "uses inline assembly"),
    ("unsafe", "uses unsafe code"),
    ("std::fs", "the sandbox has no files"),
    ("std::net", "the sandbox has no network"),
    ("std::process", "the sandbox has no processes"),
    ("std::env", "the sandbox has no environment"),
    (
        "std::time",
        "the sandbox has no clock; use the bar timestamps",
    ),
    ("std::thread", "the sandbox is single-threaded"),
    ("from_ymd", "hard-codes calendar dates"),
    (".date()", "conditions on calendar dates"),
];

/// Checks model-written source before it is compiled. Returns the reason
/// it was rejected, if it was.
pub fn check_source(source: &str) -> Result<(), String> {
    if !source.contains("export_strategy!") {
        return Err("the strategy must be registered with export_strategy!".into());
    }
    for (pattern, why) in FORBIDDEN {
        if source.contains(pattern) {
            return Err(format!("`{pattern}` is not allowed ({why})"));
        }
    }
    for line in source.lines() {
        let code = line.split("//").next().unwrap_or("");
        let trimmed = code.trim_start();
        if trimmed.starts_with("mod ") && trimmed.trim_end().ends_with(';') {
            return Err("strategies must be a single file (`mod name;` loads another)".into());
        }
        if trimmed.starts_with("#![") && !trimmed.starts_with("#![allow(") {
            return Err(format!(
                "crate attribute `{}` is not allowed",
                trimmed.trim()
            ));
        }
    }
    // Absolute timestamps (seconds, milliseconds or nanoseconds since 1970)
    // all have ten or more digits. Prices and raw fixed-point constants in a
    // strategy don't need that many, so a literal this long is almost
    // certainly a date.
    let mut digits = 0;
    for c in source.chars() {
        if c.is_ascii_digit() {
            digits += 1;
            if digits >= 10 {
                return Err(
                    "integer literals with 10 or more digits look like timestamps and are not allowed; \
                     use Price/Qty/Money::from_int or from_raw with smaller numbers, or compute large values"
                        .into(),
                );
            }
        } else if c != '_' {
            digits = 0;
        }
    }
    Ok(())
}

/// Compiles strategies in a fixed scratch crate, reusing one target
/// directory so the SDK is built once.
pub struct GuestBuilder {
    crate_dir: PathBuf,
    target_dir: PathBuf,
    cargo: PathBuf,
    timeout: Duration,
}

impl GuestBuilder {
    /// `workspace_root` is the tape repository; scratch files go under
    /// `target/lab`.
    pub fn new(workspace_root: &Path) -> Result<Self, BuildError> {
        let workspace_root = workspace_root.canonicalize()?;
        let crate_dir = workspace_root.join("target/lab/guest");
        let sdk = workspace_root.join("crates/tape-guest");
        fs::create_dir_all(crate_dir.join("src"))?;
        let manifest = format!(
            r#"# Generated by tape-lab. Strategies only supply src/lib.rs.
[package]
name = "tape-lab-guest"
version = "0.0.0"
edition = "2024"
publish = false

[lib]
crate-type = ["cdylib"]

[dependencies]
tape-guest = {{ path = {sdk:?} }}

[profile.release]
opt-level = 2
panic = "abort"
codegen-units = 16
debug = false

[workspace]
"#
        );
        fs::write(crate_dir.join("Cargo.toml"), manifest)?;
        Ok(Self {
            crate_dir,
            target_dir: workspace_root.join("target/lab/build"),
            cargo: std::env::var_os("CARGO").map_or_else(|| "cargo".into(), PathBuf::from),
            timeout: Duration::from_secs(180),
        })
    }

    /// Checks and compiles `source`, returning the WebAssembly module.
    pub fn build(&self, source: &str) -> Result<Vec<u8>, BuildError> {
        check_source(source).map_err(BuildError::Rejected)?;
        // Every builder, in this process or another, shares one scratch
        // crate, so builds take turns: a mutex for threads here and a file
        // lock for other processes (a test run alongside an experiment).
        static SCRATCH: Mutex<()> = Mutex::new(());
        let _turn = SCRATCH
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner());
        let lock = fs::File::create(self.crate_dir.join(".build.lock"))?;
        lock.lock()?;
        fs::write(self.crate_dir.join("src/lib.rs"), source)?;
        let wasm = self
            .target_dir
            .join("wasm32-unknown-unknown/release/tape_lab_guest.wasm");
        let _ = fs::remove_file(&wasm);

        let mut child = Command::new(&self.cargo)
            .args([
                "build",
                "--release",
                "--offline",
                "--quiet",
                "--message-format",
                "short",
                "--target",
                "wasm32-unknown-unknown",
            ])
            .arg("--manifest-path")
            .arg(self.crate_dir.join("Cargo.toml"))
            .arg("--target-dir")
            .arg(&self.target_dir)
            .env("CARGO_TERM_COLOR", "never")
            .stdout(Stdio::null())
            .stderr(Stdio::piped())
            .spawn()?;

        // Drain stderr while waiting: a long error list can fill the pipe
        // and block cargo before it exits.
        let reader = child.stderr.take().map(|mut pipe| {
            std::thread::spawn(move || {
                use std::io::Read;
                let mut text = String::new();
                let _ = pipe.read_to_string(&mut text);
                text
            })
        });
        let started = Instant::now();
        let status = loop {
            if let Some(status) = child.try_wait()? {
                break status;
            }
            if started.elapsed() > self.timeout {
                let _ = child.kill();
                let _ = child.wait();
                return Err(BuildError::Timeout(self.timeout));
            }
            std::thread::sleep(Duration::from_millis(50));
        };
        let stderr = reader
            .and_then(|handle| handle.join().ok())
            .unwrap_or_default();
        if !status.success() {
            // Keep the errors, drop the noise, and cap the length so the
            // repair prompt stays small.
            let errors: String = stderr
                .lines()
                .filter(|line| !line.trim().is_empty() && !line.contains("warning: "))
                .collect::<Vec<_>>()
                .join("\n");
            let errors: String = errors.chars().take(4_000).collect();
            return Err(BuildError::Compile(errors));
        }
        Ok(fs::read(wasm)?)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const OK: &str = "use tape_guest::*;\nstruct S;\nexport_strategy!(S);\n";

    #[test]
    fn accepts_plain_strategies() {
        assert_eq!(check_source(OK), Ok(()));
        let with_constants = format!("{OK}const LOT: i64 = 100_000_000; // 1.0 in raw units\n");
        assert_eq!(check_source(&with_constants), Ok(()));
    }

    #[test]
    fn rejects_ways_to_see_the_future() {
        let cases = [
            "const DATA: &str = include_str!(\"../../data/test.csv\");",
            "if bar.open_ts.as_nanos() > 1_735_689_600_000_000_000 { }",
            "const JAN_2025: i64 = 1735689600;",
            "let t = Timestamp::from_ymd(2025, 1, 1);",
            "if bar.close_ts.date().0 == 2025 { }",
            "let now = std::time::SystemTime::now();",
        ];
        for case in cases {
            let source = format!("{OK}{case}\n");
            assert!(check_source(&source).is_err(), "should reject: {case}");
        }
    }

    #[test]
    fn rejects_escapes_and_extra_files() {
        for case in [
            "unsafe { }",
            "mod helpers;",
            "#![no_std]",
            "extern crate alloc;",
        ] {
            assert!(
                check_source(&format!("{OK}{case}\n")).is_err(),
                "should reject: {case}"
            );
        }
        assert!(check_source("struct S;").is_err(), "must export a strategy");
    }
}
